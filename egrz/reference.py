#: Коды субъектов, которые в источниках встречаются как дубли основного кода.
CODE_ALIASES: dict[str, str] = {
    "95": "20",   # Чеченская Республика
    "99": "77",   # Москва
    "97": "77",
    "197": "77",
    "750": "50",
    "799": "77",
}


def _normalize_key(value: str) -> str:
    """Приводит название к форме, устойчивой к регистру, ё и пунктуации."""
    text = unicodedata.normalize("NFKC", value or "").lower().replace("ё", "е")
    text = re.sub(r"[^0-9a-zа-я]+", " ", text)
    return re.sub(r"\s+", " ", text).strip()


#: Слова-«шумы»: их отбрасывание превращает «Респ. Татарстан» в «татарстан».
_NOISE_WORDS = (
    "автономный округ", "автономная область", "автономный",
    "республика", "респ", "область", "обл", "край", "город", "гор", "г",
    "federal", "субъект", "рф", "российской федерации",
)


def _strip_noise(key: str) -> str:
    for word in _NOISE_WORDS:
        key = re.sub(rf"\b{re.escape(word)}\b", " ", key)
    return re.sub(r"\s+", " ", key).strip()


def _build_region_index() -> dict[str, tuple[str, str, str]]:
    """key -> (код, каноническое имя, федеральный округ)."""
    index: dict[str, tuple[str, str, str]] = {}

    def put(key: str, payload: tuple[str, str, str]) -> None:
        key = key.strip()
        # Первое вхождение выигрывает: канонические ключи регистрируются
        # раньше «урезанных», поэтому коллизия не переопределит точное совпадение.
        if key and key not in index:
            index[key] = payload

    for code, name, district, aliases in REGIONS:
        payload = (code, name, district)
        put(_normalize_key(name), payload)
        for alias in aliases:
            put(_normalize_key(alias), payload)

    for code, name, district, aliases in REGIONS:
        payload = (code, name, district)
        put(_strip_noise(_normalize_key(name)), payload)
        for alias in aliases:
            put(_strip_noise(_normalize_key(alias)), payload)

    return index


_REGION_INDEX = _build_region_index()

_CODE_INDEX: dict[str, tuple[str, str, str]] = {
    code: (code, name, district) for code, name, district, _ in REGIONS
}

#: Каноническое имя -> федеральный округ (для агрегатов и дашборда).
REGION_TO_DISTRICT: dict[str, str] = {name: district for _, name, district, _ in REGIONS}


def resolve_region(raw: str | None, *, code: str | None = None) -> tuple[str, str | None, str]:
    """Определяет субъект РФ по строке и/или коду.

    Возвращает ``(каноническое имя, код, федеральный округ)``. Если распознать
    не удалось — исходная строка сохраняется как есть, чтобы не терять данные,
    а округ помечается как неопределённый.
    """
    if code:
        digits = re.sub(r"\D", "", str(code))
        digits = CODE_ALIASES.get(digits, digits)
        padded = digits.zfill(2) if len(digits) == 1 else digits
        if padded in _CODE_INDEX:
            _, name, district = _CODE_INDEX[padded]
            return name, padded, district

    text = (raw or "").strip()
    if not text:
        return "Не указан", None, "Не определён"

    key = _normalize_key(text)
    for candidate in (key, _strip_noise(key)):
        hit = _REGION_INDEX.get(candidate)
        if hit:
            return hit[1], hit[0], hit[2]

    # Адрес целиком: ищем самое длинное совпадение названия внутри строки,
    # чтобы «Московская область» не проиграла подстроке «Москва».
    best: tuple[int, tuple[str, str, str]] | None = None
    for candidate_key, payload in _REGION_INDEX.items():
        if len(candidate_key) < 4:
            continue
        if re.search(rf"\b{re.escape(candidate_key)}\b", key):
            if best is None or len(candidate_key) > best[0]:
                best = (len(candidate_key), payload)
    if best:
        _, (hit_code, hit_name, hit_district) = best
        return hit_name, hit_code, hit_district

    return text, None, "Не определён"


