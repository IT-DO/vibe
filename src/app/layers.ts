/**
 * Кто кого закрывает: слой камеры и экраны поверх него.
 *
 * Живое превью лежит под всеми экранами и не перемонтируется. Значит, экран,
 * который должен его показывать, обязан быть прозрачным — иначе камера
 * работает впустую, а гость видит чёрный прямоугольник.
 *
 * Ровно это и случилось: заставка бралась за общую обёртку экранов, у
 * которой фон непрозрачный по умолчанию, и «живое зеркало» — приём, ради
 * которого человек вообще подходит к будке, — не работало ни разу.
 *
 * Правило вынесено сюда и покрыто тестами: оно про композицию экранов, а не
 * про оформление, и ошибка в нём не видна ни на типах, ни на глаз в коде.
 */

import type {SessionState} from '../features/session/machine';

type ScreenName = SessionState['name'];

/**
 * Экраны, под которыми должно просвечивать превью камеры.
 *
 * Заставка — гость видит себя ещё на подходе и невольно останавливается.
 * Съёмка — по прямому назначению.
 */
export function showsCameraBehind(screen: ScreenName): boolean {
  switch (screen) {
    case 'attract':
    case 'getReady':
    case 'countdown':
    case 'capturing':
    case 'betweenShots':
      return true;
    default:
      return false;
  }
}

/**
 * Затемнение поверх превью, 0..1.
 *
 * На заставке оно сильное: поверх кадра идёт крупный текст, и его надо
 * читать. На съёмке почти отсутствует — гость должен хорошо себя видеть.
 * На остальных экранах непрозрачное: камера там не нужна, и её ещё и
 * выключают, но заливка страхует от просвечивания на время перехода.
 */
export function scrimOpacity(screen: ScreenName): number {
  if (screen === 'attract') {
    return 0.55;
  }
  return showsCameraBehind(screen) ? 0.15 : 1;
}

/**
 * Цвет фона экрана. Прозрачный там, где под ним живое превью.
 * `undefined` означает «фон по умолчанию», то есть непрозрачный.
 */
export function screenBackground(screen: ScreenName): 'transparent' | undefined {
  return showsCameraBehind(screen) ? 'transparent' : undefined;
}
