/**
 * Шрифты приложения.
 *
 * Фотобудка на мероприятии — вещь нарядная, и типографика здесь работает
 * наравне с рамкой отпечатка: сухой системный гротеск превращает праздничную
 * будку в форму подачи заявления. Поэтому взяты два шрифта с характером:
 *
 *  - **Playfair Display** — антиква с высоким контрастом штриха, какой
 *    набирали афиши и театральные программки конца XIX века. Заголовки и
 *    название мероприятия;
 *  - **Lobster** — рукописная вывеска середины XX века, та самая, что
 *    рисовали на бортах кафе и фотоателье. Подпись на отпечатке и крупные
 *    праздничные фразы.
 *
 * Оба встроены в приложение (`assets/fonts`), а не берутся из системы:
 * набор системных шрифтов на разных прошивках Android отличается, и один и
 * тот же отпечаток вышел бы на двух планшетах разным. Кириллица есть в
 * обоих — интерфейс и подписи русские.
 *
 * Служебные надписи (админка, состояние принтера, счётчики) остаются
 * системным шрифтом: их читают быстро и вблизи, а декоративная антиква
 * замедляет чтение.
 */

/**
 * Имена семейств так, как их видит React Native после линковки ассетов: на
 * Android семейство называется по имени файла без расширения.
 *
 * Модуль намеренно ничего не импортирует из `react-native` — благодаря
 * этому имена и пути проверяются обычными тестами на Node, вместе с самими
 * файлами шрифтов.
 */
export const fontFamily = {
  /** Антиква для заголовков: название мероприятия, «Как вам?», «Спасибо!». */
  display: 'PlayfairDisplay-Bold',
  /** Та же антиква обычного начертания — для подзаголовков. */
  displayRegular: 'PlayfairDisplay-Regular',
  /** Рукописная вывеска — призыв на заставке и подпись отпечатка. */
  script: 'Lobster-Regular',
  /** Системный гротеск Android для служебного текста админки. */
  system: 'sans-serif',
} as const;

/** Файлы шрифтов внутри приложения — по ним Skia собирает подпись листа. */
export const fontAssets = {
  display: 'PlayfairDisplay-Bold.ttf',
  displayRegular: 'PlayfairDisplay-Regular.ttf',
  script: 'Lobster-Regular.ttf',
} as const;

export type FontRole = keyof typeof fontAssets;

/**
 * Путь к файлу шрифта внутри собранного приложения.
 *
 * На Android ассеты лежат в APK, и обратиться к ним можно только по схеме
 * `file:///android_asset/...` — обычного пути в файловой системе у них нет.
 */
export function fontAssetUri(role: FontRole): string {
  return `file:///android_asset/fonts/${fontAssets[role]}`;
}
