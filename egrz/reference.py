_COMPILED_RULES: tuple[tuple[str, str, re.Pattern[str]], ...] = tuple(
    (
        category,
        purpose,
        re.compile("|".join(kw.replace(" ", r"\w*\s+") for kw in keywords)),
    )
    for category, purpose, keywords in OBJECT_RULES
)

#: Полный список категорий — фасет показывает и пустые значения тоже.
OBJECT_CATEGORIES: tuple[str, ...] = tuple(
    dict.fromkeys([category for category, _, _ in OBJECT_RULES] + ["Прочее"])
)


def _match_rules(haystack: str) -> tuple[str, str] | None:
    for category, purpose, pattern in _COMPILED_RULES:
        if pattern.search(haystack):
            return category, purpose
    return None


def classify_object(name: str, address: str = "") -> tuple[str, str]:
    """Классифицирует объект по наименованию. -> (категория, назначение).

    Адрес используется только как запасной вариант: в нём попадаются слова
    вроде «ул. Школьная», которые в основном проходе дали бы ложную категорию.
    """
    by_name = _match_rules(_normalize_key(name))
    if by_name:
        return by_name
    by_address = _match_rules(_normalize_key(address)) if address else None
    if by_address:
        return by_address
    return "Прочее", "Не определено"


