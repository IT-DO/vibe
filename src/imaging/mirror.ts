/**
 * Нужно ли отражать кадр при сборке листа.
 *
 * Ловушка здесь в том, что отражение делают двое. VisionCamera для
 * фронтальной камеры зеркалит вывод сама (свойство `mirrored` по умолчанию
 * включено именно для неё), и в файле уже лежит зеркальный кадр. Если
 * композитор отразит его ещё раз, получится исходная, незеркальная картинка —
 * то есть настройка «печатать зеркально» даст ровно обратный результат.
 *
 * Поэтому решение принимается не по «с какой камеры снято», а по сравнению
 * желаемого состояния с фактическим состоянием файла.
 */

export interface MirrorDecision {
  /** Снят ли кадр нашей камерой. Чужой снимок из галереи не зеркалим. */
  readonly fromCamera: boolean;
  /** Зеркален ли кадр уже сейчас, в файле. */
  readonly fileIsMirrored: boolean;
  /** Каким его хочет видеть оператор на бумаге. */
  readonly wantMirrored: boolean;
}

/**
 * Отражать ли кадр при отрисовке.
 *
 * Возвращает true, только когда фактическое состояние расходится с желаемым.
 */
export function shouldFlip(decision: MirrorDecision): boolean {
  // Снимок из галереи принадлежит человеку и снят не нами: его ориентация
  // такая, какой он её видит у себя. Отражать чужую фотографию — брак.
  if (!decision.fromCamera) {
    return false;
  }
  return decision.wantMirrored !== decision.fileIsMirrored;
}
